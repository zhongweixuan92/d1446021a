def analyze_registrations(test_name, board_game_raw, movie_raw):
    """
    兩場活動報名整理器
    參數:
        test_name (str): 測試組別名稱
        board_game_raw (str): 桌遊體驗原始報名字串
        movie_raw (str): 電影欣賞原始報名字串
    """
    # 1. 定義固定費率 (使用 tuple 存放不可變的設定值)
    PRICES = (120, 80)  # (桌遊單價, 電影單價)

    # 2. 字串清理與轉為 set 去重
    # 規則：移除半形空白 -> 轉小寫 -> 依逗號切割 -> 轉為集合去重
    bg_set = set(board_game_raw.replace(" ", "").lower().split(","))
    mv_set = set(movie_raw.replace(" ", "").lower().split(","))

    # 3. 集合運算與名單排序 (sorted 會回傳按字母排序的 list)
    bg_sorted = sorted(bg_set)
    mv_sorted = sorted(mv_set)

    both_attended = sorted(bg_set & mv_set)       # 交集：兩場都參加
    only_bg = sorted(bg_set - mv_set)             # 差集：只參加桌遊
    only_mv = sorted(mv_set - bg_set)             # 差集：只參加電影
    total_unique_people = bg_set | mv_set         # 聯集：總不重複人數

    # 4. 計算人數、人次與金額 (使用 dict 結構化儲存統計結果)
    stats = {
        "bg_count": len(bg_set),
        "mv_count": len(mv_set),
        "total_unique": len(total_unique_people),
        "total_attendances": len(bg_set) + len(mv_set),  # 報名人次
        "bg_fee": len(bg_set) * PRICES[0],
        "mv_fee": len(mv_set) * PRICES[1],
    }
    stats["total_fee"] = stats["bg_fee"] + stats["mv_fee"]

    # 5. 字串格式化輸出摘要
    print(f"================ {test_name} ================")
    print(f"【桌遊體驗】人數：{stats['bg_count']} 人 | 應收：{stats['bg_fee']:,} 元")
    print(f"   名單：{', '.join(bg_sorted)}")
    print(f"【電影欣賞】人數：{stats['mv_count']} 人 | 應收：{stats['mv_fee']:,} 元")
    print(f"   名單：{', '.join(mv_sorted)}")
    print("-" * 45)
    print(f"• 兩場都參加 ({len(both_attended)} 人)：{', '.join(both_attended) if both_attended else '無'}")
    print(f"• 僅參加桌遊 ({len(only_bg)} 人)：{', '.join(only_bg) if only_bg else '無'}")
    print(f"• 僅參加電影 ({len(only_mv)} 人)：{', '.join(only_mv) if only_mv else '無'}")
    print("-" * 45)
    print(f"總不重複人數：{stats['total_unique']} 人")
    print(f"總報名人次 ：{stats['total_attendances']} 人次")
    print(f"兩場應收總額：{stats['total_fee']:,} 元\n")


# ================= 三組實際測試 =================

# 測試一：包含大小寫混雜、多餘空白與同場重複報名
t1_bg = " Amy, bob, AMY,  Cindy, david "
t1_mv = "BOB,  cindy, Eric, eric, Frank"
analyze_registrations("測試一：一般混合名單", t1_bg, t1_mv)

# 測試二：兩場名單完全重疊（極端情況測試）
t2_bg = "Alice, Bob"
t2_mv = "bob, ALICE, alice"
analyze_registrations("測試二：名單完全重疊", t2_bg, t2_mv)

# 測試三：兩場名單完全不重疊，且各有單人報名
t3_bg = "Zoe"
t3_mv = "Adam,  adam "
analyze_registrations("測試三：名單完全獨立", t3_bg, t3_mv)